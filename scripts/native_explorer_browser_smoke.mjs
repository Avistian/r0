// Native typed variables through the real shared explorer page; installed Chromium only.
import fs from "node:fs/promises";
import path from "node:path";
import assert from "node:assert/strict";
import {openBrowser} from "./explorer_browser.mjs";
const [port, url, directory] = process.argv.slice(2);
const browser = await openBrowser(Number(port), url, directory);
try {
  await browser.waitFor("document.getElementById('construction-family').options.length >= 6");
  await browser.evaluate(`$('construction-panel').open=true; $('construction-family').value='Native mixed graph (authored)'; $('construction-family').onchange();
    const c=JSON.parse($('construction-controls').value); c.task.rows=16;c.task.context_rows=8;$('construction-controls').value=JSON.stringify(c);`);
  await browser.click("construct");
  const before=await browser.evaluate("({archive:current.archive,episode:current.view.episode_id,source:current.view.source_task_id,schema:current.view.feature_schema,origin:current.view.target_origin})");
  assert.equal(before.origin,"native-variable-v1");
  assert.deepEqual(before.schema.map(f=>f.kind),["continuous","binary","categorical"]);
  assert.equal(await browser.evaluate("$('pair-panel').hidden && $('curve').closest('article').hidden"),true);
  await browser.evaluate("$('feature').value=2; $('feature').dispatchEvent(new Event('change'))");
  assert.equal(await browser.evaluate("$('feature-hist').textContent.includes('green')"),true);
  await browser.screenshot("native-categories.png");
  await browser.click("export");
  await browser.downloaded(`dataset-${before.source}.zip`);
  await browser.click("open");
  assert.equal(await browser.evaluate("current.view.episode_id"),before.episode);
  await browser.evaluate("$('graph-rows').value='7,0,7'");
  await browser.click("graph");
  assert.deepEqual(await browser.evaluate("generationGraph.rows"),[7,0,7]);
  await browser.click("mechanism-load");
  await browser.evaluate("$('mechanism-node').value='3'; $('mechanism-node').onchange(); const d=JSON.parse($('mechanism-domain').value);d.emission='argmax';$('mechanism-domain').value=JSON.stringify(d)");
  await browser.click("mechanism-apply");
  await browser.click("mechanism-save");
  const edit=await browser.evaluate("({path:current.edit.path,card:current.edit.card,origin:current.edit.after.target_origin})");
  assert.equal(edit.origin,"native-variable-v1");
  assert.equal(edit.card.before_episode_id,before.episode);
  assert.notEqual(edit.card.after_episode_id,before.episode);
  await browser.click("edit-open");
  await browser.click("edit-export");
  await browser.downloaded("mechanism-edit.zip");
  await browser.screenshot("native-edit.png");
  await browser.evaluate("$('construction-controls').value='{}';$('construct').click()");
  await browser.waitFor("!busy");
  assert.equal(await browser.evaluate("$('status').className"),"error");
  assert.equal(await browser.evaluate("current.view.episode_id"),before.episode);
  await browser.send("Emulation.setDeviceMetricsOverride", {width:390,height:844,deviceScaleFactor:1,mobile:true});
  assert.equal(await browser.evaluate("document.documentElement.scrollWidth > innerWidth + 2"),false);
  await browser.screenshot("native-mobile.png");
  assert.deepEqual(browser.exceptions,[]);
  await fs.writeFile(path.join(directory,"receipt.json"),JSON.stringify({before,edit,downloads:browser.downloads,exceptions:browser.exceptions},null,2));
} finally {browser.close();}
