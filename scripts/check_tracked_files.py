"""Reject Python bytecode in the Git index, including force-added ignored files."""

import subprocess
import sys
from pathlib import PurePosixPath


def main() -> int:
    paths = subprocess.check_output(["git", "ls-files", "-z"]).decode().split("\0")
    forbidden = [
        path
        for path in paths
        if PurePosixPath(path).suffix in {".pyc", ".pyo"}
        or "__pycache__" in PurePosixPath(path).parts
    ]
    if forbidden:
        print("FAIL: remove generated bytecode from the Git index:")
        print("\n".join(forbidden))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
