// node scripts/gp_explorer_browser_smoke.mjs <debug-port> <explorer-url> <evidence-dir>
import fs from "node:fs/promises";
import path from "node:path";
import assert from "node:assert/strict";
import {openBrowser} from "./explorer_browser.mjs";
const [port = "9226", url = "http://127.0.0.1:8773/", directory = "/tmp/r0-gp-browser"] = process.argv.slice(2);
const {send, evaluate, waitFor, downloaded, screenshot, click, exceptions, downloads, close} = await openBrowser(port, url, directory);
assert.equal(await evaluate("Boolean(document.getElementById('gp-options'))"), true, "conditional GP controls must exist");
await evaluate("document.getElementById('family').value='Exact Gaussian process'; document.getElementById('family').dispatchEvent(new Event('change')); {const r=JSON.parse(document.getElementById('recipe').value); Object.assign(r.task,{features:2,signal_features:1,active_features:1}); r.calibration_rows=32; r.kernels=[{kind:'matern12',length_scale:0.7}]; document.getElementById('recipe').value=JSON.stringify(r);}");
await click("generate");
await evaluate("document.getElementById('feature').value=0; document.getElementById('feature').dispatchEvent(new Event('change')); document.getElementById('curve-row').value=7; document.getElementById('curve-points').value=65; document.getElementById('gp-draws').value=3; document.getElementById('gp-seed').value='9223372036854775807'");
await click("curve");
const strict = await evaluate("curve");
assert.equal(strict.kind, "gp_conditional_curve");
assert.equal(strict.sampling.seed, "9223372036854775807");
assert.equal(strict.conditioning.approximate, false);
assert.equal(strict.original.shown_count, 64);
assert.equal(await evaluate("document.querySelectorAll('[data-kind=additional-draw]').length"), 3);
assert.equal(await evaluate("document.querySelectorAll('[data-kind=original]').length"), 64);
assert.equal(await evaluate("document.querySelectorAll('[data-kind=uncertainty]').length"), 1);
assert.equal(await evaluate("document.querySelector('#response-plot svg rect').height.baseVal.value"),350);
await screenshot("strict.png");
await evaluate("document.querySelector('#response-plot .chart-actions button').click(); document.querySelectorAll('#response-plot .chart-actions button')[1].click(); document.getElementById('curve-json').click()");
await Promise.all([downloaded("response-plot.svg"), downloaded("response-plot.png"), downloaded("response-curve.json")]);
assert.deepEqual(JSON.parse(await fs.readFile(path.join(directory, "response-curve.json"), "utf8")), strict);
for (const extension of ["svg", "png"]) await fs.copyFile(path.join(directory, `response-plot.${extension}`), path.join(directory, `strict-chart.${extension}`));
assert.match(await fs.readFile(path.join(directory,"strict-chart.svg"),"utf8"), /Strict conditioning on 96 saved support points/);
await click("curve"); assert.deepEqual(await evaluate("curve"), strict);
await evaluate("document.getElementById('gp-seed').value='42'; document.getElementById('gp-seed').dispatchEvent(new Event('change'))");
assert.equal(await evaluate("curve"), null);
assert.equal(await evaluate("document.getElementById('curve-json').hidden"), true);
await click("curve");
assert.deepEqual(await evaluate("curve.mean"), strict.mean);
assert.notDeepEqual(await evaluate("curve.draws"), strict.draws);
await evaluate("document.getElementById('feature').value=1; document.getElementById('feature').dispatchEvent(new Event('change'))");
assert.equal(await evaluate("curve"), null);
await click("curve");
const constant = await evaluate("({mean:curve.mean,sd:curve.standard_deviation,original:curve.original.row_indices})");
assert(constant.mean.every(row => row[0] === constant.mean[0][0]));
assert(constant.sd.every(row => row[0] === 0));
assert.deepEqual(constant.original,[7]);
await evaluate("{const r=JSON.parse(document.getElementById('recipe').value); r.task.task_type='multiclass'; r.task.classes=3; document.getElementById('recipe').value=JSON.stringify(r);}");
await click("generate");
await evaluate("document.getElementById('feature').value=0; document.getElementById('channel').value=2; document.getElementById('channel').dispatchEvent(new Event('change'))");
await click("curve");
assert.equal(await evaluate("curve.mean[0].length"),3);
assert.match(await evaluate("document.getElementById('response-plot').textContent"),/latent signal 2/);
await screenshot("multiclass.png");
await evaluate("{const r=JSON.parse(document.getElementById('recipe').value); r.kernels=[{kind:'rbf',length_scale:2}]; document.getElementById('recipe').value=JSON.stringify(r);}");
await click("generate");
assert.equal(await evaluate("document.getElementById('gp-approximate').checked"),false);
await evaluate("document.getElementById('curve').click()"); await waitFor("!busy");
assert.match(await evaluate("document.getElementById('status').textContent"),/rank deficient/);
assert.equal(await evaluate("document.querySelectorAll('#response-plot svg').length"),0);
await screenshot("strict-error.png");
await evaluate("document.getElementById('gp-approximate').checked=true; document.getElementById('gp-approximate').dispatchEvent(new Event('change'))");
await click("curve");
const approximate = await evaluate("curve");
assert(approximate.conditioning.approximate);
assert(approximate.conditioning.retained_rank < approximate.conditioning.support_count);
assert.match(await evaluate("document.getElementById('response-plot').textContent"),/Approximate:/);
await screenshot("approximate.png");
await evaluate("document.querySelector('#response-plot .chart-actions button').click(); document.querySelectorAll('#response-plot .chart-actions button')[1].click()");
await Promise.all([downloaded("response-plot.svg",2),downloaded("response-plot.png",2)]);
for (const extension of ["svg", "png"]) await fs.copyFile(path.join(directory, `response-plot.${extension}`), path.join(directory, `approximate-chart.${extension}`));
assert.match(await fs.readFile(path.join(directory,"approximate-chart.svg"),"utf8"),/Approximate:/);
assert.equal(await evaluate("[...document.querySelectorAll('#response-plot svg text')].every(text => {const box=text.getBBox(); return box.x>=0 && box.x+box.width<=480;})"),true);
await send("Emulation.setDeviceMetricsOverride", {width:390,height:844,deviceScaleFactor:1,mobile:true});
await screenshot("mobile.png");
assert.equal(await evaluate("document.documentElement.scrollWidth > innerWidth"),false);
await evaluate("document.getElementById('curve-points').value=257; document.getElementById('curve-points').dispatchEvent(new Event('change')); document.getElementById('curve').click()"); await waitFor("!busy");
assert.match(await evaluate("document.getElementById('status').textContent"),/2..256/);
assert.equal(await evaluate("curve"),null);
assert.deepEqual(exceptions,[]);
await fs.writeFile(path.join(directory,"receipt.json"),JSON.stringify({url,browser:await send("Browser.getVersion"),node:process.version,strict_identity:strict.episode_id,strict_conditioning:strict.conditioning,seed:strict.sampling.seed,approximate_identity:approximate.episode_id,approximate_conditioning:approximate.conditioning,checks:["separate original/mean/band/additional draw marks","large seed JSON export","replay","changed seed changes draws only","stale controls clear view","constant irrelevant feature","multiclass channel","strict rank failure","explicit approximation and exported labels","SVG/PNG completed downloads","mobile no overflow","point limit"],downloads,exceptions},null,2));
close(); console.log(`GP browser checks passed; evidence in ${directory}`);
