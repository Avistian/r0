// node scripts/pair_explorer_browser_smoke.mjs <debug-port> <explorer-url> <evidence-dir>
import fs from "node:fs/promises";
import path from "node:path";
import assert from "node:assert/strict";
import {openBrowser} from "./explorer_browser.mjs";
const [port = "9226", url = "http://127.0.0.1:8775/", directory = "/tmp/r0-pair-browser"] = process.argv.slice(2);
const {send, evaluate, waitFor, downloaded, screenshot, click, exceptions, downloads, close} = await openBrowser(port, url, directory);
assert.equal(await evaluate("Boolean(document.getElementById('pair-create'))"), true, "saved comparison controls must exist");

await evaluate("document.getElementById('seed').value='9223372036854775807'; {const r=JSON.parse(document.getElementById('recipe').value); Object.assign(r,{rows:128,context_rows:80,noise_ratio:0.2}); document.getElementById('recipe').value=JSON.stringify(r);}");
await click("generate");
const base = await evaluate("current.view.episode_id");
await evaluate("document.getElementById('pair-value').value=0.8");
await click("pair-create");
const noise = await evaluate("current.pair");
assert.equal(await evaluate("current.view.episode_id"),base);
assert.equal(noise.card.after.residual_std / noise.card.before.residual_std,4);
assert.equal(noise.card.seed,"9223372036854775807");
assert.match(await evaluate("document.getElementById('pair-title').textContent"),/0.2 → 0.8/);
async function sameAxes() {
  assert.equal(await evaluate("JSON.stringify({...document.querySelector('#pair-before-plot svg').dataset}) === JSON.stringify({...document.querySelector('#pair-after-plot svg').dataset})"),true);
  assert.equal(await evaluate("JSON.stringify([...document.querySelectorAll('#pair-before-plot circle')].map(p=>[p.dataset.row,p.getAttribute('cx')])) === JSON.stringify([...document.querySelectorAll('#pair-after-plot circle')].map(p=>[p.dataset.row,p.getAttribute('cx')]))"),true);
}
await sameAxes();
await evaluate("document.getElementById('pair-panel').scrollIntoView({block:'start'}); document.querySelector('#pair-after-plot circle').focus()");
await send("Input.dispatchKeyEvent", {type:"keyDown",key:"Enter",code:"Enter",windowsVirtualKeyCode:13});
await send("Input.dispatchKeyEvent", {type:"keyUp",key:"Enter",code:"Enter",windowsVirtualKeyCode:13});
assert.equal(await evaluate("JSON.parse(document.getElementById('pair-row').textContent).before.index === JSON.parse(document.getElementById('pair-row').textContent).after.index"),true);
await screenshot("noise.png");
await evaluate("document.querySelector('#pair-before-plot .chart-actions button').click(); document.querySelectorAll('#pair-after-plot .chart-actions button')[1].click(); document.getElementById('pair-card').click()");
await click("pair-export");
await Promise.all([downloaded("pair-before-plot.svg"),downloaded("pair-after-plot.png"),downloaded("comparison-card.json"),downloaded(`comparison-${noise.card.pair_id}.zip`)]);
assert.match(await fs.readFile(path.join(directory,"comparison-card.json"),"utf8"),/9223372036854775807/);
assert.match(await fs.readFile(path.join(directory,"pair-before-plot.svg"),"utf8"),/Before · Noise \/ signal 0.2 · 128\/128 rows/);
await evaluate("document.getElementById('pair-value').value=0.9; document.getElementById('seconds').value=0.001; document.getElementById('pair-create').click()");
await waitFor("!busy");
assert.match(await evaluate("document.getElementById('status').textContent"),/Timed out: True/);
assert.equal(await evaluate("current.pair.card.pair_id"),noise.card.pair_id);
await evaluate("document.getElementById('seconds').value=60; document.getElementById('pair-intervention').value='irrelevant'; document.getElementById('pair-intervention').dispatchEvent(new Event('change')); document.getElementById('pair-value').value=16");
await click("pair-create");
const irrelevant = await evaluate("current.pair");
assert(irrelevant.card.required_equalities.targets);
assert.equal(irrelevant.after.view.features.length,16);
assert.equal(await evaluate("document.getElementById('pair-feature').options.length"),8);
await sameAxes();
await evaluate("document.getElementById('pair-intervention').value='sparsity'; document.getElementById('pair-intervention').dispatchEvent(new Event('change')); document.getElementById('pair-value').value=2");
await click("pair-create");
assert.equal(await evaluate("current.pair.card.variance_control"),"analytic_unit_variance");
await screenshot("sparsity.png");
await evaluate("document.getElementById('family').value='Polynomial'; document.getElementById('family').dispatchEvent(new Event('change'))");
await click("generate");
assert.equal(await evaluate("document.getElementById('pair-results').hidden"),true);
await evaluate("document.getElementById('pair-intervention').value='sparsity'; document.getElementById('pair-intervention').dispatchEvent(new Event('change')); document.getElementById('pair-value').value=2; document.getElementById('pair-create').click()");
await waitFor("!busy");
assert.match(await evaluate("document.getElementById('status').textContent"),/allow_estimated_variance/);
assert.equal(await evaluate("current.pair"),null);
await evaluate("document.getElementById('pair-estimate').checked=true");
await click("pair-create");
assert.match(await evaluate("document.getElementById('pair-variance').textContent"),/Equality of true expected variances is not established/);
await screenshot("estimated-sparsity.png");
await evaluate("document.getElementById('family').value='Linear'; document.getElementById('family').dispatchEvent(new Event('change')); {const r=JSON.parse(document.getElementById('recipe').value); Object.assign(r,{task_type:'multiclass',classes:3}); document.getElementById('recipe').value=JSON.stringify(r);}");
await click("generate");
assert.equal(await evaluate("document.getElementById('pair-estimate').checked"),false);
await click("pair-create");
const classification = await evaluate("current.pair");
assert(classification.after.view.rows.every(row=>row.probabilities.every(p=>Math.abs(p-1/3)<1e-15)));
await evaluate("document.getElementById('pair-channel').value=2; document.getElementById('pair-channel').dispatchEvent(new Event('change'))");
await sameAxes();
assert.equal(await evaluate("document.querySelectorAll('#pair-counts tbody tr').length"),3);
assert.equal(await evaluate("document.querySelector('#pair-after-plot svg').dataset.yLow"),"0");
assert.equal(await evaluate("document.querySelector('#pair-after-plot svg').dataset.yHigh"),"1");
await screenshot("classification.png");
const savedPath = noise.path;
await evaluate(`document.getElementById('pair-path').value=${JSON.stringify(savedPath)}`);
await click("pair-open");
assert.equal(await evaluate("current.pair.card.pair_id"),noise.card.pair_id);
assert.equal(await evaluate("current.view.episode_id"),base);
await sameAxes();
await send("Emulation.setDeviceMetricsOverride", {width:390,height:844,deviceScaleFactor:1,mobile:true});
await evaluate("document.getElementById('pair-panel').scrollIntoView({block:'start'})");
await screenshot("mobile.png");
assert.equal(await evaluate("document.documentElement.scrollWidth > innerWidth"),false);
assert.deepEqual(exceptions,[]);
await fs.writeFile(path.join(directory,"receipt.json"),JSON.stringify({url,browser:await send("Browser.getVersion"),node:process.version,noise:noise.card,irrelevant:irrelevant.card,classification:classification.card,checks:["same axes and matched rows","same base after intervention","all four interventions","strict variance refusal and explicit estimate","failed generation keeps prior comparison","large seed download","SVG/PNG/ZIP/JSON completed downloads","keyboard row inspection","classification channels and counts","saved comparison reopen","new base clears comparison","mobile no overflow"],downloads,exceptions},null,2));
close(); console.log(`Pair browser checks passed; evidence in ${directory}`);
